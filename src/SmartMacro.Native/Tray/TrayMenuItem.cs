namespace SmartMacro.Native.Tray;

/// <summary>
/// Один пункт контекстного меню иконки в трее.
/// </summary>
/// <param name="Id">
/// Стабильный идентификатор, который выбирает вызывающая сторона и который возвращается
/// обратно через <see cref="Win32TrayIcon.ItemClicked"/>. Win32-идентификаторы команд
/// позиционные и заново раздаются при каждом <see cref="Win32TrayIcon.Start"/>, поэтому
/// подписчики разбирают именно этот Id.
/// </param>
/// <param name="Text">Надпись в меню. Может содержать любой Unicode (весь путь — UTF-16).</param>
/// <param name="IsDefault">
/// Помечает пункт как выбранный по умолчанию (рисуется жирным) и делает его тем действием,
/// которое выполняется по двойному клику на иконке. Такой пункт должен быть не более одного;
/// если их несколько, побеждает первый.
/// </param>
public sealed record TrayMenuItem(string Id, string Text, bool IsDefault = false);
