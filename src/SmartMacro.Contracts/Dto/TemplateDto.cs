namespace SmartMacro.Contracts.Dto;

/// <summary>
/// Один файл шаблона машинного зрения в том виде, в каком его перечисляет демон, — БЕЗ картинки.
///
/// <b>Разделение «список — это метаданные, картинка — по требованию» здесь и есть протокол.</b>
/// Одна такая запись весит десятки байт, так что весь список демона (сейчас четырнадцать
/// шаблонов, в макете тридцать один) укладывается в пару килобайт и приезжает одним запросом при
/// входе в режим. Сами PNG — килобайты каждый, и труба у них общая с потоком событий прогона:
/// соединение сериализует записи, поэтому пачка картинок, отправленных «на всякий случай», встала
/// бы перед событиями работающего макроса. Поэтому байты едут ровно за тот шаблон, который
/// пользователь выбрал, и ровно тогда, когда он его выбрал, — см.
/// <see cref="TemplateImageDto"/>.
///
/// <see cref="Width"/> и <see cref="Height"/> лежат здесь по той же причине: рамку превью и
/// подпись «112×34» панель рисует, ещё не имея ни одного пикселя.
/// </summary>
/// <param name="Set">
/// Набор, которому принадлежит шаблон (подпапка <c>templates/</c>), либо <c>null</c> —
/// одиночный шаблон в корне дерева. Это же и различает двух потребителей: одиночные шаблоны
/// называют <c>FindElement</c>/<c>WaitForElement</c>, набор целиком называет
/// <c>RecognizeTag</c>.
/// </param>
/// <param name="Name">
/// Имя шаблона = основа имени файла. ЭТО ТА САМАЯ СТРОКА, которую несёт нода: для одиночного
/// шаблона — <c>FindElementNode.Template</c>, для члена набора — тег, который навесит
/// <c>RecognizeTagNode</c>. Регистр важен.
/// </param>
/// <param name="Width">Ширина в пикселях; 0, если файл не разобрался как PNG.</param>
/// <param name="Height">Высота в пикселях; 0, если файл не разобрался как PNG.</param>
/// <param name="Bytes">
/// Размер файла на диске. Панель сверяет его с <see cref="TemplateLimits.MaxImageBytes"/> и не
/// просит превью, которое всё равно отвергнут.
/// </param>
public sealed record TemplateDto(string? Set, string Name, int Width, int Height, long Bytes);

/// <summary>
/// Байты одного шаблона — ответ на <c>GetTemplateImage</c>.
/// </summary>
/// <param name="Set">Набор запрошенного шаблона, как в запросе.</param>
/// <param name="Name">Имя запрошенного шаблона, как в запросе.</param>
/// <param name="Png">
/// Содержимое файла. По проводу едет как base64 — так <c>System.Text.Json</c> сериализует
/// <c>byte[]</c>, — то есть на треть больше самого файла; при потолке в
/// <see cref="TemplateLimits.MaxImageBytes"/> это по-прежнему одно короткое сообщение.
/// </param>
public sealed record TemplateImageDto(string? Set, string Name, byte[] Png)
{
    /// <summary>
    /// <c>true</c>, когда этот ответ описывает именно <paramref name="set"/>/<paramref name="name"/>.
    ///
    /// Ответ несёт эхо запроса не ради корреляции — та идёт по <c>Id</c> конверта, — а ради
    /// ГОНКИ ВЫДЕЛЕНИЯ: пользователь щёлкает по списку быстрее, чем отвечает демон, и ответ на
    /// предпоследний выбор приходит после ответа на последний. Без этой сверки в превью
    /// осталась бы картинка не того шаблона, который подсвечен в списке.
    /// </summary>
    public bool Describes(string? set, string name) =>
        string.Equals(Set, set, StringComparison.Ordinal) && string.Equals(Name, name, StringComparison.Ordinal);
}

/// <summary>Пределы, которые оба конца обязаны знать одинаково.</summary>
public static class TemplateLimits
{
    /// <summary>
    /// Потолок на превью одного шаблона.
    ///
    /// Существует потому, что труба у превью общая с потоком событий прогона, а
    /// <c>IpcConnection</c> сериализует записи: многомегабайтная строка base64 задержала бы за
    /// собой пачку событий работающего макроса, а очередь соединения в 256 событий не бесконечна
    /// (переполнение = отключение клиента). Настоящие шаблоны — это вырезки игрового интерфейса
    /// в десятки килобайт, так что мегабайт — это примерно тридцатикратный запас, а упереться в
    /// него может только полноэкранный скриншот, положенный в папку по ошибке.
    ///
    /// Проверяют обе стороны: панель не просит того, что заведомо не пролезет (размер файла она
    /// уже знает из списка), демон отвергает всё, что всё-таки попросили, — файл мог вырасти
    /// между перечислением и запросом.
    /// </summary>
    public const long MaxImageBytes = 1024 * 1024;
}
