namespace SmartMacro.Contracts.Dto;

/// <summary>
/// Уровень записи журнала на проводе.
///
/// Повторяет <c>Serilog.Events.LogEventLevel</c> член в член и по порядку — но НЕ является им:
/// Contracts не знает про Serilog и знать не должен (панель тоже, хотя у неё свой Serilog для
/// собственного файла лога). Числовые значения заданы явно, потому что панель сравнивает их
/// операцией «не ниже» при фильтрации, и порядок здесь — часть контракта, а не деталь
/// объявления.
///
/// <b>Незнакомый уровень должен деградировать, а не ломать</b> — то же правило, что у
/// <see cref="RunEventKind"/>: панель старше своего демона рисует такую запись как обычную,
/// а не теряет весь поток.
/// </summary>
public enum LogLevelDto
{
    /// <summary>Самая подробная отладка. Демон её сейчас не пишет вовсе.</summary>
    Verbose = 0,

    /// <summary>Отладка. Единственный источник, включённый на этом уровне, — <c>SmartMacro.GameWindows</c>.</summary>
    Debug = 1,

    /// <summary>Обычный ход дела — уровень демона по умолчанию.</summary>
    Information = 2,

    /// <summary>Что-то пошло не так, но работа продолжается.</summary>
    Warning = 3,

    /// <summary>Операция не удалась.</summary>
    Error = 4,

    /// <summary>Процесс уходит.</summary>
    Fatal = 5,
}

/// <summary>
/// Одна строка журнала демона.
///
/// <b>Уже отрисованная, а не шаблон со свойствами.</b> Serilog внутри держит запись как
/// <c>MessageTemplate</c> плюс словарь свойств, и передавать её так было бы «честнее». Но тогда
/// панели пришлось бы носить с собой Serilog и его форматтер, чтобы собрать ту же строку, —
/// а это ровно та зависимость, от которой стадия 3 избавляла процесс интерфейса. Отрисовка на
/// стороне демона стоит одного лишнего прохода по шаблону поверх двух, которые он и так делает
/// для консоли и файла.
///
/// <see cref="Exception"/> отделено от <see cref="Message"/> по той же причине, по которой они
/// разделены в шаблоне вывода файла: стек в двадцать строк, вклеенный в сообщение, ломает
/// строчную вёрстку списка. Панель показывает его отдельным свёрнутым блоком.
/// </summary>
/// <param name="Seq">
/// Сквозной номер записи в пределах жизни демона, возрастающий строго.
///
/// <b>Нужен против ДВОЕНИЯ на подписке, а не для порядка.</b> <c>SubscribeLog</c> сначала
/// включает поток соединению, и только потом снимает предысторию с кольца, — иначе между двумя
/// этими действиями образовалась бы дыра, которую уже ничем не заполнить. Расплата за
/// правильный порядок в том, что запись, попавшая точно между ними, приедет и в предыстории, и
/// в первой живой пачке. Панель отбрасывает всё, чей номер не больше последнего номера
/// предыстории; без номера отличить повтор от настоящей второй такой же строки было бы нельзя.
/// </param>
/// <param name="Timestamp">Когда запись сделана, в местном времени демона со смещением.</param>
/// <param name="Level">Уровень.</param>
/// <param name="Source">
/// <c>SourceContext</c> — полное имя типа, который писал. <c>null</c> у записей, сделанных
/// через статический <c>Log</c> без <c>ForContext</c> (так пишет <c>Program</c> на старте).
/// </param>
/// <param name="Message">Отрисованное сообщение, без уровня, времени и источника.</param>
/// <param name="Exception">Исключение со стеком, как его печатает <c>ToString()</c>, либо <c>null</c>.</param>
public sealed record LogEntryDto(
    long Seq,
    DateTimeOffset Timestamp,
    LogLevelDto Level,
    string? Source,
    string Message,
    string? Exception);

/// <summary>
/// Нагрузка пуша <c>LogEntries</c>: всё, что демон записал с прошлого сброса.
///
/// Форма намеренно повторяет <see cref="RunEventBatch"/> — это ВТОРАЯ подписка на том же русле,
/// а не второй механизм. Причина склейки та же и даже острее: очередь соединения в 256 записей
/// отключает клиента, который не поспевает, а журнал шумнее событий прогона —
/// <c>SmartMacro.GameWindows</c> крутится на <c>Debug</c>, и одна активация окна игры пишет
/// несколько строк.
/// </summary>
/// <param name="Entries">Записи в том порядке, в каком их сделал демон.</param>
/// <param name="Dropped">
/// Сколько записей выбросили до этой пачки из-за переполнения собственной очереди демона.
/// Ненулевое значение означает дыру в ленте, и панель обязана об этом сказать. Движок при этом
/// не ждал ни микросекунды: логирует его в том числе и обход макроса, идущий между двумя
/// сообщениями живой игре.
/// </param>
public sealed record LogEntryBatch(IReadOnlyList<LogEntryDto> Entries, int Dropped);

/// <summary>Пределы ленты журнала, которые обоим концам полагается знать одинаково.</summary>
public static class LogLimits
{
    /// <summary>
    /// Сколько последних записей демон держит в кольце и отдаёт подписчику как предысторию.
    ///
    /// <b>Кольцо здесь есть, а у событий прогона его намеренно нет</b>, и разница не в
    /// небрежности. События прогона между обрывом и переподключением никто не записывал —
    /// съём показаний был выключен, — так что буфер был бы заведомо протухшим. Журнал же
    /// пишется независимо от того, смотрит ли кто-нибудь, и «Лог» открывают ровно затем, чтобы
    /// увидеть, что только что произошло. Панель, пришедшая к работающему демону и получившая
    /// пустой экран, не показала бы ничего именно в тот момент, ради которого её открыли.
    ///
    /// Тысяча — это порядка получаса работы демона на холостом ходу и несколько минут активной
    /// автоматизации с <c>GameWindows</c> на <c>Debug</c>. По памяти это сотни килобайт, то
    /// есть проценты от одиннадцати мегабайт частных страниц демона (стадия 4A), и они платятся
    /// всегда — это и есть цена за то, чтобы предыстория была.
    /// </summary>
    public const int HistoryCapacity = 1000;
}
