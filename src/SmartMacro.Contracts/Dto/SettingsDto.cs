using SmartMacro.Contracts.Settings;

namespace SmartMacro.Contracts.Dto;

/// <summary>
/// Настройки плюс то, что настройками не является, но показывается на том же экране.
///
/// Три поля рядом с <see cref="Settings"/> — не украшение, а разделение по владельцу:
/// <see cref="Settings"/> лежит в файле и переживает перезапуск, а <see cref="LogLevel"/> живёт
/// только в текущем процессе, и пути известны лишь демону. Слить их в одну запись значило бы
/// показать уровень журнала как сохраняемую настройку, каковой он намеренно НЕ является.
/// </summary>
/// <param name="Settings">Содержимое файла настроек — то, что панель правит.</param>
/// <param name="LogLevel">
/// Живой минимальный уровень Serilog у демона.
///
/// <b>Не из файла настроек и в него не попадёт.</b> Постоянный уровень остаётся в
/// <c>appsettings.json</c>: если демон падает на чтении настроек, отладить это можно только тем
/// уровнем, что был известен ДО. Экран настроек двигает <c>LoggingLevelSwitch</c> на лету, и
/// сдвиг живёт до перезапуска демона — интерфейс обязан это сказать.
/// </param>
/// <param name="SettingsFilePath">Полный путь к <c>settings.json</c> — для подписи и для «показать файл».</param>
/// <param name="FolderPath">Папка демона: её открывает кнопка «Открыть папку».</param>
public sealed record SettingsSnapshotDto(
    AppSettings Settings,
    LogLevelDto LogLevel,
    string SettingsFilePath,
    string FolderPath);

/// <summary>Чем кончилась одна проверка среды.</summary>
public enum DiagnosticStatus
{
    /// <summary>Всё в порядке. Рисуется одной компактной строкой, а не карточкой.</summary>
    Ok = 0,

    /// <summary>Работать будет, но не так, как задумано. Например, масштабирование экрана не 100%.</summary>
    Warning = 1,

    /// <summary>Не работает. Ради этого состояния блок диагностики и существует.</summary>
    Failed = 2,
}

/// <summary>
/// Результат одной проверки среды.
///
/// <b>Почти все отказы этого приложения средовые</b> — права, отсутствующий файл шаблона,
/// масштабирование экрана, — и проявляются они не сообщением об ошибке, а тем, что макрос
/// «просто не работает». Блок диагностики существует, чтобы превратить это в предложение,
/// которое можно прочитать.
/// </summary>
/// <param name="Id">Устойчивый ключ проверки — по нему панель вешает на карточку нужную кнопку.</param>
/// <param name="Status">Итог.</param>
/// <param name="Title">Одна строка: что проверяли (при <see cref="DiagnosticStatus.Ok"/>) или что сломано.</param>
/// <param name="Detail">
/// Подробность. У успеха — короткое измеренное значение («отвечает, 4 мс»); у отказа — причина и
/// последствие, потому что «UIPI» само по себе никому ничего не говорит.
/// </param>
public sealed record DiagnosticDto(string Id, DiagnosticStatus Status, string Title, string Detail);

/// <summary>Устойчивые идентификаторы проверок. Общие для обоих концов: демон их ставит, панель по ним решает, какую кнопку нарисовать.</summary>
public static class DiagnosticIds
{
    /// <summary>Права демона против уровня целостности окон игры (UIPI).</summary>
    public const string Elevation = "elevation";

    /// <summary>Шаблоны, на которые ссылаются макросы, но которых нет на диске.</summary>
    public const string Templates = "templates";

    /// <summary>Масштабирование экрана: шаблоны пиксель-в-пиксель сняты при 100%.</summary>
    public const string DisplayScale = "display-scale";

    /// <summary>Глобальные аккорды: сколько из привязанных удалось зарегистрировать.</summary>
    public const string Hotkeys = "hotkeys";

    /// <summary>Папка приложения на запись — там лежат макросы, настройки и журнал.</summary>
    public const string FolderWritable = "folder-writable";

    /// <summary>
    /// Совпадает ли зарегистрированный автозапуск с галочками.
    ///
    /// Существует потому, что регистрация может не удаться, а панель об этом не узнает: задачу в
    /// Планировщике создаёт только администратор. Без этой проверки получалось бы ровно то, что
    /// волна D4 чинила у горячих клавиш, — галочка поставлена, интерфейс чист, не происходит
    /// ничего.
    /// </summary>
    public const string AutoStart = "autostart";

    /// <summary>
    /// Канал с демоном. <b>Единственная проверка, которую делает панель, а не демон</b>: он не
    /// может честно измерить время ответа самому себе.
    /// </summary>
    public const string Channel = "channel";
}
