using SmartMacro.Native;

namespace SmartMacro.Vision;

// Настройки ClassMatcher — область обрезки в окне характеристик, где отрисовано
// «Класс: <имя>», и пороги бинаризации и сопоставления шаблонов.
//
// Пользователь один раз открывает игровое окно характеристик (по умолчанию клавиша C) в
// фиксированном положении; эти координаты адресуют только область текста значения (ту часть,
// где стоит имя класса, например «Жрец»). Сопоставление заранее отрисованных PNG с именами
// классов по этой области возвращает подошедший тег (основу имени файла шаблона).
//
// И область, и пороги настраиваются в appsettings.json, чтобы пользователь мог подогнать их под
// своё разрешение и масштаб интерфейса без пересборки.
public sealed class ClassMatcherOptions
{
    // Запасной прямоугольник обрезки; им пользуется только диагностика
    // DebugBinarizeClassRegion — живой путь берёт область из ноды RecognizeTag. Значения по
    // умолчанию соответствуют авторскому скриншоту окна характеристик в 2K. Чтобы найти
    // координаты на своём разрешении, наведите курсор в игре и запустите макрос:
    // CursorPositionProvider запишет в лог клиентскую точку.
    public ScreenRect Region { get; init; } = new(3200, 1060, 160, 35);

    // Отсечка по яркости для бинаризации — текст класса в окне характеристик отрисован светлым
    // по тёмной панели; 200 сохраняет ядро букв и отбрасывает градиент подложки. Та же логика
    // порога, что исторически была у NameMatcher (там стояло 240, потому что плашка с именем
    // почти белая). Текст панели характеристик тусклее, поэтому значение по умолчанию ниже.
    public double LuminanceThreshold { get; init; } = 200.0;

    // Отсечка по оценке Cv2.MatchTemplate CCoeffNormed. Для плашек с именами хватало 0.6; текст
    // значения класса короче и структурно менее уникален, так что если на практике полезут
    // ложные срабатывания, порог, возможно, придётся поднять.
    public double MatchThreshold { get; init; } = 0.6;
}
