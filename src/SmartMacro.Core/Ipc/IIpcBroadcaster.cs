using SmartMacro.Contracts.Ipc;

namespace SmartMacro.Ipc;

/// <summary>
/// Способность <see cref="IpcServer"/> «толкнуть это каждой подключённой панели», вынесенная в
/// отдельный интерфейс ради двух потребителей, которым нужна она, но не нужен сам сервер:
/// <see cref="IpcRequestDispatcher"/> (обработка <c>RequestActivate</c>) и контроллер трея у
/// демона (вывести вперёд уже запущенную панель).
///
/// Диспетчер не может просто принять <see cref="IpcServer"/> — сервер конструируется ВМЕСТЕ с
/// диспетчером, и DI увидел бы цикл. Вместо этого сервер вручает диспетчеру вещателя сам (см.
/// <see cref="IpcRequestDispatcher.AttachBroadcaster"/>); трей, из которого сервер никто не
/// конструирует, разрешает этот интерфейс обычным порядком.
/// </summary>
public interface IIpcBroadcaster
{
    /// <summary>
    /// Ставит <paramref name="evt"/> в очередь каждому живому соединению. Не блокирует и
    /// никогда не бросает — клиента, который не поспевает, отключают, а не докладывают об этом
    /// вызывающему.
    /// </summary>
    void Broadcast(IpcEvent evt);

    /// <summary>
    /// Ставит <paramref name="evt"/> в очередь только тем соединениям, которые попросили поток
    /// событий прогона через <c>SubscribeRunEvents</c>.
    ///
    /// Отделено от <see cref="Broadcast"/>, потому что это единственное частое событие в
    /// протоколе: отправить его клиенту, который ни о чём не просил, значит вывалить на него
    /// шквал, разбирать который у него нет причин, — а расплата за неразбор очереди здесь
    /// отключение.
    /// </summary>
    void BroadcastToRunSubscribers(IpcEvent evt);
}
