namespace SmartMacro.Ipc;

/// <summary>
/// Тот кусочек состояния протокола, который принадлежит ОДНОМУ соединению, а не движку.
///
/// Всё остальное в каталоге для клиента бессостоятельно: запрос называет, чего он хочет, и
/// ответ один и тот же, кто бы ни спросил. С подписками не так — «шлите мне события прогона»
/// есть факт о конкретной трубе, и весь смысл того, что подписка добровольная, в том, что
/// второй клиент, который ни о чём не просил, так ничего и не получает. Сессию вручают
/// диспетчеру рядом с запросом, чтобы на <c>SubscribeRunEvents</c> можно было ответить, не
/// заставляя <see cref="IpcRequestDispatcher"/> узнавать, что такое соединение.
///
/// Подписок здесь ДВЕ, и они независимы: события прогона панель включает, пока на экране
/// «Макросы», а ленту журнала — пока на экране «Лог». Один общий флаг заставил бы каждый из
/// режимов оплачивать трафик другого, а это два самых частых сообщения протокола.
///
/// Третьим состоянием стала ПРИОСТАНОВКА ХОТКЕЕВ, и попала она сюда позже остальных — потому что
/// её здесь не было, а быть обязано. <c>SuspendHotkeys</c> правил состояние ДЕМОНА, и снять его
/// умел только ответный <c>ResumeHotkeys</c>; панель же уходит не только закрытием окна («Снять
/// задачу», падение — и путь, описанный в этом же протоколе: демон САМ выбрасывает клиента,
/// переставшего разбирать очередь событий). Тогда демон оставался работать с нулём
/// зарегистрированных аккордов, и каждая горячая клавиша молча ничего не делала до перезапуска.
/// Довод ровно тот же, по которому счёт подключённых отладчиков живёт на фронте
/// <see cref="SetRunEventSubscription"/>: состояние движка, которое способна снять только панель,
/// не имеет права пережить её смерть.
///
/// <c>null</c> в тестах диспетчера, которые гоняют каталог без сервера под ним; оба
/// нуждающихся в сессии обработчика при её отсутствии вежливо отказывают.
///
/// Команды отладчика волны D5 (пауза / шаг / до ноды) адресуют обход, а не соединение, и сам
/// интерфейс от них действительно не вырос. Но читателей у него стало два:
/// <c>DebugCommand</c> отклоняет команду от клиента, не подписанного на события прогона
/// (<see cref="WantsRunEvents"/>), потому что счёт подключённых отладчиков — это и есть
/// гарантия того, что припаркованный обход есть кому распустить. Команда от соединения вне
/// этого счёта могла бы поставить обход на паузу, с которой его никто уже не снимет. Фильтр
/// «следить только за этим обходом» на клиента жил бы здесь же, если бы объёмы такое когда-
/// нибудь оправдали.
/// </summary>
public interface IIpcSession
{
    /// <summary>Получает ли это соединение поток <c>RunEvents</c>.</summary>
    bool WantsRunEvents { get; }

    /// <summary>
    /// Включает или выключает поток для этого соединения. Идемпотентно — счётчик подписчиков,
    /// по которому движок решает, работать ли ему вообще, не имеет права поехать оттого, что
    /// клиент попросил дважды.
    /// </summary>
    void SetRunEventSubscription(bool enabled);

    /// <summary>Получает ли это соединение ленту <c>LogEntries</c>.</summary>
    bool WantsLog { get; }

    /// <summary>
    /// Включает или выключает ленту журнала для этого соединения. Идемпотентно по той же
    /// причине, что и <see cref="SetRunEventSubscription"/>.
    /// </summary>
    void SetLogSubscription(bool enabled);

    /// <summary>
    /// Берёт или отдаёт аренду приостановки глобальных аккордов ОТ ИМЕНИ ЭТОГО СОЕДИНЕНИЯ.
    ///
    /// Идемпотентно по соединению (одна аренда, сколько бы раз клиент ни попросил), а сколько
    /// соединений её держат — считает <c>IHotkeyRegistration</c>. Разделение несущее: булев флаг
    /// на соединение не даёт одному клиенту утечь второй арендой, а счётчик поверх не даёт
    /// уходящей панели вернуть аккорды, пока у второй открыт редактор.
    ///
    /// Асинхронно, потому что ответ обязан означать «сделано»: панель открывает ловушку аккорда
    /// сразу после ответа на <c>SuspendHotkeys</c>, а список отказов перечитывает сразу после
    /// ответа на <c>ResumeHotkeys</c>.
    /// </summary>
    /// <param name="enabled"><c>true</c> — взять аренду, <c>false</c> — отдать.</param>
    /// <param name="cancellationToken">Срабатывает, когда соединение закрывается.</param>
    Task SetHotkeySuspensionAsync(bool enabled, CancellationToken cancellationToken = default);
}
