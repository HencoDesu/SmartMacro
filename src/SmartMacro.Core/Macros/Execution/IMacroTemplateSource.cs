namespace SmartMacro.Macros.Execution;

/// <summary>
/// Откуда прогон берёт шаблоны машинного зрения.
///
/// <b>Разрешение шаблонов ПОРУННОЕ, а не глобальное, и это следствие бандлов (§5.7).</b> До
/// волны F2 <c>MacroPrimitives</c> держал один провайдер на процесс и разрешал имена по общему
/// дереву <c>templates/</c>: какой макрос спрашивает — не имело значения. Теперь шаблон лежит
/// внутри бандла и принадлежит ровно одному макросу, так что одно и то же имя у двух макросов —
/// это два разных файла. Источник поэтому ставится ОДИН РАЗ, в <c>Orchestrator.RunAsync</c>, и
/// едет в <see cref="MacroRunContext.Templates"/>.
///
/// Лексическая область видимости при этом не нужна — и это не упрощение, а свойство формата:
/// <b>прогон никогда не покидает свой бандл</b>. Под-макросы в F4 будут лежать внутри него же, а
/// наружу вызовов нет, поэтому дочерние обходы наследуют тот же источник, что и родитель, ровно
/// как наследуют наблюдателя и отладчика.
///
/// <b>Кто резолвит.</b> Имена разрешает ОБХОДЧИК (<see cref="MacroExecutor"/>), а в
/// <see cref="IMacroPrimitives"/> уезжают уже байты. Иначе источник пришлось бы протаскивать
/// параметром в каждый вызов примитива, а слой примитивов — «ввод, зрение и косметика по hwnd» —
/// начал бы знать про формат файла макроса.
/// </summary>
public interface IMacroTemplateSource
{
    /// <summary>
    /// Один шаблон по имени — то, что несут <c>FindElementNode.Template</c> и
    /// <c>WaitForElementNode.Template</c>. Регистр важен.
    /// </summary>
    /// <returns>Байты PNG или <c>null</c>, если такого шаблона в бандле нет.</returns>
    byte[]? TryGetTemplate(string templateName);

    /// <summary>
    /// Именованный набор в виде «тег → байты PNG» — то, что несёт
    /// <c>MatchTemplateSetNode.TemplateSet</c>. Неизвестный набор даёт пустой словарь, и тогда нода
    /// просто никогда ни с чем не совпадёт.
    /// </summary>
    IReadOnlyDictionary<string, byte[]> GetSet(string setName);
}
