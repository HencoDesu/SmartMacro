using SmartMacro.Macros.Model;

namespace SmartMacro.Macros.Execution;

/// <summary>
/// Состояние прогона, которое передают в <see cref="MacroExecutor.RunAsync"/>. Корневой
/// контекст строит слой триггеров (хоткей → окна нет, появление процесса → новое окно);
/// <see cref="RunSubmacroNode"/> порождает дочерние контексты с копией переменных и глубиной 1.
/// </summary>
public sealed record MacroRunContext
{
    /// <summary>
    /// Окно, по которому работают действия без цели и условные ноды. <c>null</c> у прогонов от
    /// хоткея — ноды, которым окно необходимо, в этом случае обрывают прогон.
    /// </summary>
    public IntPtr? ContextWindow { get; init; }

    /// <summary>Переменные прогона. Слой триггеров засевает <c>cursor</c> через <see cref="MacroVariables.ForTrigger"/>.</summary>
    public required MacroVariables Variables { get; init; }

    /// <summary>
    /// Откуда прогон берёт шаблоны машинного зрения. Ставится ОДИН РАЗ, в
    /// <c>Orchestrator.RunAsync</c>, и наследуется дочерними обходами: прогон никогда не покидает
    /// свой бандл, поэтому лексическая область видимости не нужна (§5.7, F2).
    ///
    /// <c>null</c> означает «шаблонов нет» — так выглядит любой тест, написанный до F2, и так же
    /// выглядит прогон макроса, чей бандл не прочитался. Ноды зрения в этом случае уходят по «не
    /// найдено» / «не совпало» со строкой в журнале, а не обрывают прогон: ветка на этот исход в
    /// графе уже есть, и вести себя иначе, чем при отсутствующем файле шаблона, было бы для
    /// автора макроса неожиданностью.
    /// </summary>
    public IMacroTemplateSource? Templates { get; init; }

    /// <summary>
    /// Под-макросы бандла, по их <c>Guid</c> (волна F4). Ставится ОДИН РАЗ, там же, где
    /// <see cref="Templates"/>, и по той же причине: под-макросы лежат внутри бандла, и прогон
    /// его не покидает. Наследуется дочерними обходами — не ради вложенности (её нет), а чтобы
    /// нести источник рядом с шаблонами одним и тем же способом.
    ///
    /// <c>null</c> = «под-макросов нет»; так выглядит любой тест, написанный до F4, и прогон
    /// макроса, чей бандл не прочитался. Нода вызова в этом случае ОБРЫВАЕТ прогон, а не уходит
    /// куда-то ещё: у вызова нет ветки «не найдено», и притвориться, что функция отработала,
    /// было бы враньём.
    /// </summary>
    public IReadOnlyDictionary<Guid, MacroGraph>? Submacros { get; init; }

    /// <summary>
    /// Имя МАКРОСА (бандла), которому принадлежит этот обход, либо <c>null</c> — «взять имя
    /// обходимого графа».
    ///
    /// Нужно потому, что у обхода ПОД-макроса имя графа — это подпись функции, а не макроса, а
    /// адресуются по макросу двое: точки останова и переключатель прогонов в панели. Корневой
    /// контекст поле не ставит, и <c>null</c> означает ровно «граф и есть макрос».
    /// </summary>
    public string? MacroName { get; init; }

    /// <summary>
    /// Под-макрос, который сейчас обходят, либо <c>null</c> — граф верхнего уровня. ТРЕТЬЯ
    /// КООРДИНАТА точки останова: пары «макрос + нода» с волны F4 не хватает.
    /// </summary>
    public Guid? SubmacroId { get; init; }

    /// <summary>
    /// Отслеживаемый прогон, к которому относится этот контекст, из
    /// <see cref="MacroRunHandle.RunId"/>. Носится исключительно ради того, чтобы события
    /// прогона можно было привязать к строке в «Прогонах»; сам walker его никогда не читает.
    /// <see cref="Guid.Empty"/>, когда вызывающий гоняет исполнителя мимо реестра, — а так
    /// делают только тесты.
    /// </summary>
    public Guid RunId { get; init; }

    /// <summary>
    /// Глубина: 0 у прогона от триггера, 1 у обхода под-макроса. Больше единицы не бывает —
    /// под-макросы плоские (<see cref="MacroSubmacro"/>), и именно это делает циклы невозможными
    /// по построению. Прежние <c>MaxDepth = 4</c> и цепочка вызовов для детекта циклов по именам
    /// удалены вместе с межмакросными вызовами.
    /// </summary>
    public int Depth { get; init; }

    /// <summary>
    /// Крючок прогресса: вызывается с ПОДПИСЬЮ ноды, когда walker в неё входит, — реестр
    /// прогонов через него выставляет наружу текущую ноду, не связывая себя с исполнителем.
    /// Подпись, а не id: единственный потребитель — колонка «где сейчас» в режиме «Прогоны».
    /// </summary>
    public Action<string>? OnNodeEntered { get; init; }

    /// <summary>
    /// Структурированный канал прогресса: ноды, исходы, подробности, длительности. <c>null</c>
    /// означает «без съёма показаний» — именно в таком виде выглядит любой тест, написанный до
    /// D3b.
    ///
    /// Отдельно от <see cref="OnNodeEntered"/>, а не вместо него: тот крючок кормит реестр
    /// прогонов, представляет собой одну строку состояния и для каждого под-обхода стреляет по
    /// одному и тому же общему на весь прогон дескриптору. Этот же канал — ПООБХОДНЫЙ, и именно
    /// за ним следует канва.
    /// </summary>
    public IMacroRunObserver? Observer { get; init; }

    /// <summary>
    /// Канал управления отладчика (волна D5): пауза, шаг, до ноды, точки останова. <c>null</c>
    /// означает «отлаживать нельзя» — именно так выглядит любой тест, написанный до D5, и по
    /// сути так же выглядит хост без панели.
    ///
    /// Двойник <see cref="Observer"/> — тот докладывает, этот решает, можно ли обходу идти
    /// дальше, — и наследуется под-обходами так же, поэтому каждая ветка разветвления
    /// <see cref="RunSubmacroNode"/> отлаживается по отдельности.
    /// </summary>
    public IMacroDebugger? Debugger { get; init; }
}
