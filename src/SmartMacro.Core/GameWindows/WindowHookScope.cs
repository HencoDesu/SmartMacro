namespace SmartMacro.GameWindows;

/// <summary>
/// Вторая половина скобки пробуждения. Реализует <see cref="GameWindow"/>; наружу интерфейс
/// вынесен только затем, чтобы <see cref="WindowHookScope"/> не знал о конкретном классе.
/// </summary>
public interface IWindowHookHolder
{
    /// <summary>
    /// Отпускает одну ссылку. <b>Токена НЕ принимает, и это не упущение.</b> Заморозка есть
    /// уборка за побудкой, а отменять уборку по тому же токену, который её и вызвал, значит не
    /// делать её ровно в том случае, ради которого она и нужна: «■ Стоп» посреди тика зрения
    /// оставил бы клиента размороженным до настоящей смены фокуса пользователем.
    /// </summary>
    ValueTask ExitHookAsync();

    /// <summary>Синхронный близнец — для <see cref="IGameWindow.CaptureScreenshot"/>.</summary>
    void ExitHook();
}

/// <summary>
/// Область пробуждения окна: пока она открыта, окно разбужено; когда закрылась последняя — оно
/// заморожено обратно.
///
/// <code>
/// await using var scope = await window.EnterHookAsync(HookOn.Input, ct);
/// await window.PressKeyAsync(key);
/// </code>
///
/// <b>Область, а не пара вызовов, — и это единственное, что здесь по-настоящему важно.</b> Пара
/// «разбудить / заморозить обратно» уже подводила: ревью нашло четыре скобки, у которых вторая
/// половина стояла просто следующей строкой, и отмена посреди тика зрения оставляла до десяти
/// клиентов PW рендерить в фоне — навсегда, потому что чинить их было уже некому (обход-то
/// отменён). <c>await using</c> закрывает скобку компилятором, так что правило перестаёт держаться
/// на внимательности того, кто пишет следующего вызывающего.
///
/// На этом же свойстве стоит затвор отладчика: он потому и может парковать обход МЕЖДУ нодами, что
/// к моменту возврата управления в <c>MacroExecutor</c> все области закрыты и ни одно окно не
/// разбужено. Поэтому область обязана оставаться ВНУТРИ <c>IMacroPrimitives</c> — поднятая в
/// исполнитель, она выглядела бы опрятнее и позволила бы паузе бросить клиента размороженным.
///
/// <b>Пустая область законна</b> и означает «скобки нет»: у процесса нет хука либо хук не
/// срабатывает вокруг этой операции. Такая область не будит и не замораживает — ровно то, что
/// делал прежний путь с <c>ActivationLParam = null</c>.
///
/// Структура, а не класс: область открывается на каждое нажатие клавиши, а обход, за которым никто
/// не смотрит, не должен выделять память ни на ноду. Оба <c>Dispose</c> объявлены публично, чтобы
/// <c>using</c>/<c>await using</c> звали их напрямую, без упаковки.
/// </summary>
public readonly struct WindowHookScope : IAsyncDisposable, IDisposable
{
    private readonly IWindowHookHolder? _holder;

    internal WindowHookScope(IWindowHookHolder holder) => _holder = holder;

    /// <summary><c>true</c>, когда область действительно держит окно разбуженным.</summary>
    public bool IsHolding => _holder is not null;

    /// <summary>Отпускает ссылку; последняя замораживает окно обратно.</summary>
    public ValueTask DisposeAsync() => _holder?.ExitHookAsync() ?? ValueTask.CompletedTask;

    /// <summary>Синхронный близнец для синхронных путей захвата.</summary>
    public void Dispose() => _holder?.ExitHook();
}
