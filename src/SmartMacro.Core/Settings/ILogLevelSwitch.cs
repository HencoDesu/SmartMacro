using SmartMacro.Contracts.Dto;

namespace SmartMacro.Settings;

/// <summary>
/// Минимальный уровень журнала демона — единственная ручка экрана настроек, которая НЕ
/// сохраняется.
///
/// <b>Почему уровень остался в <c>appsettings.json</c>, вопреки общему правилу ужать его до
/// загрузочного минимума.</b> Настройки читает <c>SettingsStore</c>; если демон падает или
/// путается именно на этом чтении, единственный уровень, которым можно расследовать поломку, —
/// тот, что был известен ДО неё. Переехав уровень в <c>settings.json</c>, настройка сломала бы
/// возможность диагностировать собственную поломку — а это худший вид зависимости, какой можно
/// завести.
///
/// Отсюда и форма: экран настроек двигает уровень НА ЛЕТУ, ничего не переписывая, и сдвиг живёт
/// до перезапуска демона. Интерфейс обязан это сказать — иначе пользователь поставит Debug,
/// перезапустит демон и решит, что настройка не работает.
///
/// Интерфейсом объявлено потому, что реализация — это <c>LoggingLevelSwitch</c> из Serilog, а
/// <b>у Core нет ссылки на Serilog и не должно появиться</b>: тот же шов, что у
/// <c>IpcLogSink</c>, живущего в демоне по той же причине.
/// </summary>
public interface ILogLevelSwitch
{
    /// <summary>
    /// Текущий минимальный уровень. Присвоение действует немедленно на все стоки сразу —
    /// консоль, файл и ленту режима «Лог».
    /// </summary>
    LogLevelDto Current { get; set; }
}
