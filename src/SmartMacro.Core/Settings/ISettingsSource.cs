using SmartMacro.Contracts.Settings;

namespace SmartMacro.Settings;

/// <summary>
/// Живые настройки для тех, кто их читает, — без права записи и без знания о файле.
///
/// Существует, потому что до этой волны каждая ручка движка приезжала через
/// <c>IOptions&lt;T&gt;</c>, а тот вычисляется один раз на старте: любая правка требовала
/// перезапуска демона, и это было записано в <c>CLAUDE.md</c> отдельной ловушкой. Экран настроек
/// поверх такой механики раздражал бы сильнее блокнота, поэтому потребители теперь читают
/// <see cref="Current"/> В МОМЕНТ ИСПОЛЬЗОВАНИЯ, а не запоминают значение в конструкторе.
///
/// <b>Правило для потребителя ровно одно:</b> ничего отсюда не кэшировать в поле. Снимок
/// неизменяемый и читается одной ссылкой, так что чтение на каждом тике опроса или на каждом
/// сопоставлении не стоит ничего, а запомненное значение — это ровно тот перезапуск, от которого
/// уходили.
///
/// Отделено от <c>SettingsStore</c> тем же швом, что <c>IMacroRunner</c> от оркестратора: чтобы
/// потребителя можно было прогнать в тесте, не заводя файла на диске.
/// </summary>
public interface ISettingsSource
{
    /// <summary>Текущий снимок. Неизменяемый; между двумя чтениями может смениться целиком.</summary>
    AppSettings Current { get; }

    /// <summary>
    /// Поднимается после каждой смены настроек — сохранения из панели, сброса к умолчаниям или
    /// правки файла блокнотом.
    ///
    /// Нужен НЕ всем: тот, кто читает <see cref="Current"/> по месту, узнаёт о смене сам.
    /// Подписываются только те, кому надо что-то СДЕЛАТЬ (согласовать автозапуск с реестром,
    /// разослать снимок панелям).
    /// </summary>
    event Action<AppSettings>? SettingsChanged;
}
