using SmartMacro.Contracts.Dto;

namespace SmartMacro.Hotkeys;

/// <summary>
/// Выключение и обратное включение глобальных аккордов демона. Реализуется
/// <see cref="HotkeyListener"/>.
///
/// Почему эта операция вообще видна в протоколе: Win32 <c>RegisterHotKey</c> проглатывает
/// нажатия уже зарегистрированного аккорда — WM_HOTKEY получает окно-владелец, и клавишу больше
/// не видит никто. То есть пока в процессе UI на экране висит выбор хоткея, ровно те сочетания,
/// которые пользователь скорее всего и хочет переназначить, до него бы не доходили. UI
/// оборачивает выбор в <c>SuspendHotkeys</c> / <c>ResumeHotkeys</c>.
///
/// <b>Приостановка — это АРЕНДА, а не выключатель.</b> Панелей протокол допускает несколько, и
/// каждая держит приостановку всё то время, что у неё на экране «Макросы». Поэтому
/// <see cref="SuspendAsync"/> и <see cref="ResumeAsync"/> ведут СЧЁТЧИК держателей, а не флаг:
/// уход одной панели не имеет права вернуть аккорды, пока у второй открыт редактор, — иначе
/// <c>RegisterHotKey</c> снова начал бы проглатывать ровно то сочетание, которое она в этот
/// момент ловит. Парность вызовов обеспечивает <c>IpcServer.ClientConnection</c> (по одной аренде
/// на соединение, снимается на разрыве); здесь только арифметика.
///
/// Объявлено интерфейсом по той же причине, что и <c>IMacroRunner</c>, — ради шва для тестов:
/// настоящий <see cref="HotkeyListener"/> владеет двумя Win32-мониторами.
/// </summary>
public interface IHotkeyRegistration
{
    /// <summary>Берёт аренду приостановки: снимает регистрацию со всех аккордов, если она первая.</summary>
    Task SuspendAsync(CancellationToken cancellationToken = default);

    /// <summary>
    /// Отдаёт аренду: последний уходящий регистрирует всё заново по ТЕКУЩЕЙ библиотеке макросов.
    /// Вызов без взятой аренды ничего не делает.
    /// </summary>
    Task ResumeAsync(CancellationToken cancellationToken = default);

    /// <summary>
    /// Держит ли кто-нибудь приостановку прямо сейчас, то есть «глобальных аккордов сейчас
    /// зарегистрировано ноль».
    ///
    /// Существует ради диагностики среды. «Проверить среду» отвечает на вопрос «почему макрос
    /// просто не работает», и без этого свойства спросить было НЕЧЕГО: при пустом
    /// <see cref="Failures"/> и целых графах карточка хоткеев зеленела словами «занято N из N»,
    /// хотя в этот момент не было занято ни одного. Экран, существующий ради этого вопроса, не
    /// имеет права на такой ответ.
    /// </summary>
    bool IsSuspended { get; }

    /// <summary>
    /// Аккорды, которые были привязаны к макросу, но которые <c>RegisterHotKey</c> отверг при
    /// последней попытке регистрации; зачем это вообще кому-то нужно, см.
    /// <see cref="HotkeyFailureDto"/>.
    ///
    /// Намеренно НЕ очищается на время приостановки: панель держит приостановку всё то время,
    /// что на экране режим «Макросы», а это ровно тот момент, когда она хочет это нарисовать, —
    /// и «мы минуту назад всё разрегистрировали» не есть ответ на вопрос «свободен ли этот
    /// аккорд».
    /// </summary>
    IReadOnlyList<HotkeyFailureDto> Failures { get; }
}
