namespace SmartMacro.Macros.Model;

/// <summary>
/// Под-макрос: кусок графа, выделенный в подобие функции, и живущий ВНУТРИ бандла своего
/// родителя (<c>submacro/{Guid}.json</c>).
///
/// <b>Зачем он появился (волна F4).</b> До него <c>RunMacroNode</c> звал любой макрос библиотеки
/// ПО ИМЕНИ — то есть отданный другому человеку файл молча не работал, если у получателя не
/// оказывалось макроса с таким именем. Ровно эта беда и есть причина всего формата <c>.hsm</c>:
/// шаблоны переехали внутрь бандла в F2, вызовы — здесь. Межмакросных вызовов больше нет.
///
/// Три правила, и все три — по построению, а не по договорённости:
/// <list type="bullet">
///   <item><b>Плоско.</b> Родитель зовёт под-макрос, под-макрос — никого. Циклы становятся
///     невозможны, и вместе с ними ушли детект циклов по цепочке имён и предел вложенности ≤ 4,
///     которые <c>MacroExecutor</c> держал ради них. Рекурсия в редакторе макросов — ружьё,
///     которое выстрелит, и её никто не просил.</item>
///   <item><b>Без триггеров.</b> Хоткей на функции превращает её в макрос верхнего уровня.
///     Валидатор такой триггер отвергает ошибкой, а <c>HotkeyListener</c> смотрит только на
///     верхний уровень.</item>
///   <item><b>Без своих шаблонов.</b> Папка <c>templates/</c> одна, на уровне бандла; под-макрос
///     пользуется родительской. Иначе появился бы второй уровень разрешения имён ради случая,
///     которого нет.</item>
/// </list>
///
/// <b>Ссылка на под-макрос — по <see cref="Id"/>, а не по имени</b>, и это ровно то же решение,
/// что для нод (<see cref="MacroNode"/>): по имени переименование ломало бы родителя, и пришлось
/// бы либо запрещать переименование, либо возвращать обход графа с перенацеливанием — механику,
/// которую переход нод на <c>Guid</c> как раз и удалил. Два механизма идентичности в одной модели
/// — это два места, где надо помнить правило.
///
/// <b>Отличие от макроса верхнего уровня</b>, у которого идентичность — имя ФАЙЛА (§5.7):
/// под-макрос файлом не является в том смысле, в каком является макрос. Его не отдают, не
/// переименовывают проводником и не запускают снаружи; его называет ребро внутри того же бандла.
/// Поэтому здесь работает общее правило проекта, а исключение остаётся ровно одно — на бандл.
/// </summary>
/// <param name="Id">Личность под-макроса. Она же — основа имени файла внутри <c>submacro/</c>.</param>
/// <param name="Graph">
/// Граф под-макроса. Обычный <see cref="MacroGraph"/>, и это намеренно: валидатор, исполнитель,
/// анализы переменных и шаблонов, канва и авто-раскладка работают по нему без единой правки.
/// Его <see cref="MacroGraph.Name"/> — ПОДПИСЬ под-макроса (то, что видно в библиотеке и в
/// выпадающем списке ноды), а <see cref="MacroGraph.Triggers"/> обязан быть пуст.
/// </param>
public sealed record MacroSubmacro(Guid Id, MacroGraph Graph)
{
    /// <summary>Подпись под-макроса — имя его графа.</summary>
    public string Name => Graph.Name;
}
