using SmartMacro.Native;

namespace SmartMacro.App.Services;

/// <summary>
/// Область поиска вокруг вырезанного шаблона.
///
/// <b>Область, совпадающая с шаблоном пиксель в пиксель, — это не «найти», а «проверить, что оно
/// ровно здесь».</b> Сопоставление скользит шаблоном по области; когда они одного размера,
/// позиция ровно одна, и сдвиг элемента интерфейса на один пиксель роняет оценку ниже порога.
/// Поэтому вырез идёт точно по выделению, а <c>Region</c> ноды получает то же выделение С
/// ЗАПАСОМ.
///
/// <b>Запас постоянный, а не доля от выделения</b>, потому что терпимость, которая нужна на
/// самом деле, измеряется в пикселях сдвига, а не в процентах предмета. Двадцать пять процентов
/// от вырезки в 600 px дали бы 150 px запаса с каждой стороны — область в полтора раза шире
/// нужного и во столько же более медленное сопоставление; те же двадцать пять процентов от
/// иконки в 24 px дали бы 6 px, то есть почти ничего.
/// </summary>
public static class SearchRegion
{
    /// <summary>
    /// Запас с КАЖДОЙ стороны выделения, в пикселях клиентской области.
    ///
    /// Шестнадцать — это то место, где обе цены ещё малы. Шаблон 100×40 в области 132×72 даёт
    /// 33×33 = 1089 позиций скольжения вместо одной: разница между «проверить» и «найти», и всё
    /// ещё меньше миллисекунды. Вчетверо больший запас дал бы 129×129 ≈ 16 600 позиций ради
    /// терпимости, о которой никто не просил, а заодно и заметно больший шанс, что похожий кусок
    /// интерфейса наберёт выше настоящего.
    ///
    /// Число это <b>отправная точка, а не приговор</b>: все четыре поля области остаются в
    /// инспекторе, и ужать их до точных координат (или, наоборот, растянуть на пол-экрана) —
    /// одно движение.
    /// </summary>
    public const int Margin = 16;

    /// <summary>
    /// Выделение с запасом, обрезанное по клиентской области кадра.
    ///
    /// Обрезка обязательна: выделение у самого края экрана иначе дало бы отрицательные координаты
    /// или ширину за пределами кадра, а сопоставление такую область молча подожмёт само — то есть
    /// в инспекторе стояло бы одно, а искалось бы в другом.
    /// </summary>
    /// <param name="selection">Что пользователь выделил, в клиентских координатах кадра.</param>
    /// <param name="frameWidth">Ширина кадра; <c>0</c> и меньше — «не знаем», тогда обрезки по правому краю нет.</param>
    /// <param name="frameHeight">Высота кадра; то же самое.</param>
    public static ScreenRect Around(ScreenRect selection, int frameWidth, int frameHeight)
    {
        var left = Math.Max(0, selection.X - Margin);
        var top = Math.Max(0, selection.Y - Margin);
        var right = selection.X + selection.Width + Margin;
        var bottom = selection.Y + selection.Height + Margin;

        if (frameWidth > 0)
        {
            right = Math.Min(right, frameWidth);
        }

        if (frameHeight > 0)
        {
            bottom = Math.Min(bottom, frameHeight);
        }

        return new ScreenRect(left, top, Math.Max(0, right - left), Math.Max(0, bottom - top));
    }
}
