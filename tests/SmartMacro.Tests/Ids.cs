using System.Security.Cryptography;
using System.Text;

// Корневое пространство имён теста намеренно: помощник нужен и Macros, и ViewModels, и Ipc, а
// C# ищет имена и во внешних пространствах, так что ни одному файлу не приходится его импортировать.
namespace SmartMacro.Tests;

/// <summary>
/// Стабильный <see cref="Guid"/> по короткому строковому ключу — единственная уступка тестов
/// переходу нод на guid'ы.
///
/// Проверяют тесты ПОВЕДЕНИЕ ГРАФА, а не формат идентификатора, поэтому переписывать их на
/// <c>Guid.NewGuid()</c> с локальными переменными значило бы утопить то, что они на самом деле
/// утверждают, в объявлениях. С этим помощником <c>Id = Ids.Of("n1"), Next = Ids.Of("n2")</c>
/// читается ровно так же, как читалось <c>Id = "n1", Next = "n2"</c>, — и ровно так же
/// сравнивается в ожиданиях.
///
/// Детерминированность здесь несущая, а не удобная: ключ пишут независимо в нескольких местах
/// одного теста (нода, ребро в неё, ожидаемое значение), и совпасть они обязаны без того, чтобы
/// кто-то держал общий словарь.
/// </summary>
internal static class Ids
{
    /// <summary>Guid, отвечающий этому ключу. MD5 берётся не ради стойкости, а ради ровно 16 байт.</summary>
    public static Guid Of(string key) => new(MD5.HashData(Encoding.UTF8.GetBytes(key)));
}
